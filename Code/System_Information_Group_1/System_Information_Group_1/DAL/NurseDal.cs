using MySqlConnector;
using System;
using System.Collections.Generic;
using System_Information_Group_1.Model;

namespace System_Information_Group_1.DAL;
/// <summary>
/// The data access layer in the system for the nurse table in the database. This class provides methods to retrieve nurse data based on person ID or nurse ID.
/// </summary>
public class NurseDal
{
    #region Methods    
    /// <summary>
    /// Gets the nurse with person identifier.
    /// </summary>
    /// <param name="id">The identifier.</param>
    /// <returns>the nurse with the person ID</returns>
    public Nurse GetNurseWithPersonId(int id)
    {
        using var connection = new MySqlConnection(Connection.ConnectionString());
        connection.Open();
        var query = "select * from nurse where person_id = @id;";
        using var command = new MySqlCommand(query, connection);
        command.Parameters.Add("@id", MySqlDbType.Int32).Value = id;
        using var reader = command.ExecuteReader();
        var nurseIdOrdinal = reader.GetOrdinal("nurse_id");
        var personIdOrdinal = reader.GetOrdinal("person_id");

        
        return reader.Read() ? createNurse(reader, nurseIdOrdinal, personIdOrdinal) : throw new ArgumentNullException(nameof(reader), "reader returned no results");
    }
    /// <summary>
    /// Gets the nurse with nurse identifier.
    /// </summary>
    /// <param name="id">The identifier.</param>
    /// <returns>The nurse with the specified nurse ID</returns>
    public Nurse GetNurseWithNurseId(int id)
    {
        using var connection = new MySqlConnection(Connection.ConnectionString());
        connection.Open();
        var query = "select * from nurse where nurse_id = @id;";
        using var command = new MySqlCommand(query, connection);
        command.Parameters.Add("@id", MySqlDbType.Int32).Value = id;
        using var reader = command.ExecuteReader();
        var personIdOrdinal = reader.GetOrdinal("person_id");
        var nurseIdOrdinal = reader.GetOrdinal("nurse_id");


        return reader.Read() ? createNurse(reader, nurseIdOrdinal, personIdOrdinal) : throw new ArgumentNullException(nameof(reader), "reader returned no results");

    }

    /// <summary>
    /// Creates a new nurse row for the given person id. The nurse_id is auto-generated by the database and returned inside the Nurse object.
    /// </summary>
    /// <param name="personId">Person identifier to link to the new nurse.</param>
    /// <returns>Newly created Nurse with generated nurse id.</returns>
    public Nurse CreateNurse(int personId)
    {
        using var connection = new MySqlConnection(Connection.ConnectionString());
        connection.Open();

        var insertQuery = "insert into nurse (person_id) values (@personId);";
        using (var command = new MySqlCommand(insertQuery, connection))
        {
            command.Parameters.Add("@personId", MySqlDbType.Int32).Value = personId;
            command.ExecuteNonQuery();
        }

        using var idCommand = new MySqlCommand("select last_insert_id();", connection);
        var inserted = System.Convert.ToInt32(idCommand.ExecuteScalar());

        return new Nurse(personId, inserted);
    }

    /// <summary>
    /// Updates the person_id for an existing nurse identified by nurse_id.
    /// </summary>
    /// <param name="nurseId">The nurse identifier.</param>
    /// <param name="newPersonId">The new person identifier to set.</param>
    /// <returns>True if a row was updated; otherwise false.</returns>
    public bool UpdateNursePersonId(int nurseId, int newPersonId)
    {
        using var connection = new MySqlConnection(Connection.ConnectionString());
        connection.Open();

        var updateQuery = "update nurse set person_id = @personId where nurse_id = @nurseId;";
        using var command = new MySqlCommand(updateQuery, connection);
        command.Parameters.Add("@personId", MySqlDbType.Int32).Value = newPersonId;
        command.Parameters.Add("@nurseId", MySqlDbType.Int32).Value = nurseId;

        var rows = command.ExecuteNonQuery();
        return rows > 0;
    }

    public List<NurseDisplay> GetNurseBy(string firstName, string lastName, DateTime? dateOfBirth)
    {
        List<NurseDisplay> nurses = new List<NurseDisplay>();

        
        if (string.IsNullOrWhiteSpace(firstName) && string.IsNullOrWhiteSpace(lastName) && !dateOfBirth.HasValue)
        {
            return nurses;
        }

        using var connection = new MySqlConnection(Connection.ConnectionString());
        connection.Open();

        
        var query = "select * from nurse inner join person on nurse.person_id = person.person_id where 1=1";

        if (!string.IsNullOrWhiteSpace(firstName))
        {
            query += " and person.first_name like @firstName";
        }

        if (!string.IsNullOrWhiteSpace(lastName))
        {
            query += " and person.last_name like @lastName";
        }

        if (dateOfBirth.HasValue)
        {
            query += " and date(person.date_of_birth) = @dateOfBirth";
        }

        query += " order by person.last_name, person.first_name;";

        using var command = new MySqlCommand(query, connection);

        if (!string.IsNullOrWhiteSpace(firstName))
        {
            command.Parameters.Add("@firstName", MySqlDbType.VarChar).Value = $"{firstName.Trim()}%";
        }

        if (!string.IsNullOrWhiteSpace(lastName))
        {
            command.Parameters.Add("@lastName", MySqlDbType.VarChar).Value = $"{lastName.Trim()}%";
        }

        if (dateOfBirth.HasValue)
        {
            command.Parameters.Add("@dateOfBirth", MySqlDbType.Date).Value = dateOfBirth.Value.Date;
        }

        using var reader = command.ExecuteReader();

        var personIdOrdinal = reader.GetOrdinal("person_id");
        var nurseIdOrdinal = reader.GetOrdinal("nurse_id");
        var firstNameIdOrdinal = reader.GetOrdinal("first_name");
        var lastNameIdOrdinal = reader.GetOrdinal("last_name");
        var dateOfBirthIdOrdinal = reader.GetOrdinal("date_of_birth");
        var contactPhoneNumberIdOrdinal = reader.GetOrdinal("contact_phone_number");
        var addressIdOrdinal = reader.GetOrdinal("address");
        var genderIdOrdinal = reader.GetOrdinal("gender");
        var zipOrdinal = reader.GetOrdinal("zip");
        var cityOrdinal = reader.GetOrdinal("city");
        var stateOrdinal = reader.GetOrdinal("state");
        

        while (reader.Read())
        {
            NurseDisplay nurseDisplay = createNurseDisplay(reader, personIdOrdinal, nurseIdOrdinal, firstNameIdOrdinal,
                lastNameIdOrdinal, dateOfBirthIdOrdinal, contactPhoneNumberIdOrdinal, addressIdOrdinal,
                genderIdOrdinal, zipOrdinal, cityOrdinal, stateOrdinal);

            nurses.Add(nurseDisplay);
        }

        return nurses;
    }

    private static NurseDisplay createNurseDisplay(MySqlDataReader reader, int personIdOrdinal, int nurseIdOrdinal,
        int firstNameIdOrdinal, int lastNameIdOrdinal, int dateOfBirthIdOrdinal, int contactPhoneNumberOrdinal,
        int addressOrdinal, int genderOrdinal, int zipOrdinal, int cityOrdinal, int stateOrdinal)
    {
        return new NurseDisplay(
            reader.GetFieldValueCheckNull<int>(nurseIdOrdinal),
            reader.GetFieldValueCheckNull<int>(personIdOrdinal),
            reader.GetFieldValueCheckNull<String>(firstNameIdOrdinal),
            reader.GetFieldValueCheckNull<String>(lastNameIdOrdinal),
            reader.GetFieldValueCheckNull<DateTime>(dateOfBirthIdOrdinal),
            reader.GetFieldValueCheckNull<String>(genderOrdinal),
            reader.GetFieldValueCheckNull<String>(contactPhoneNumberOrdinal),
            reader.GetFieldValueCheckNull<String>(addressOrdinal),
            reader.GetFieldValueCheckNull<String>(zipOrdinal),
            reader.GetFieldValueCheckNull<String>(cityOrdinal),
            reader.GetFieldValueCheckNull<String>(stateOrdinal)
        );
    }

    private static Nurse createNurse(MySqlDataReader reader, int nurseIdOrdinal, int personIdOrdinal)
    {
        return new Nurse(
            reader.GetFieldValueCheckNull<int>(personIdOrdinal),
            reader.GetFieldValueCheckNull<int>(nurseIdOrdinal)
        );
    }

    

    #endregion
}